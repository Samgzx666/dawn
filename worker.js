let HTML_CACHE = null;
function getHtml() {
  if (!HTML_CACHE) {
    const bin = atob(B64);
    const bytes = Uint8Array.from(bin, (c) => c.charCodeAt(0));
    HTML_CACHE = new TextDecoder().decode(bytes);
  }
  return HTML_CACHE;
}

const json = (obj, status = 200) =>
  new Response(JSON.stringify(obj), {
    status,
    headers: { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" },
  });

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === "/api/ping") {
      return json({
        hasKey: !!env.SERPER_KEY,
        hasCode: !!env.ACCESS_CODE,
        codeOk: !!env.ACCESS_CODE && request.headers.get("x-access-code") === env.ACCESS_CODE,
      });
    }

    if (url.pathname === "/api/search") {
      if (request.method !== "POST") return json({ error: "Método no permitido" }, 405);
      if (!env.ACCESS_CODE || request.headers.get("x-access-code") !== env.ACCESS_CODE) {
        return json({ error: "Código de acceso incorrecto" }, 401);
      }
      if (!env.SERPER_KEY) return json({ error: "Falta el secreto SERPER_KEY en Cloudflare" }, 500);

      let b;
      try { b = await request.json(); } catch (e) { return json({ error: "JSON inválido" }, 400); }
      const q = String(b.q || "").slice(0, 400);
      if (!q) return json({ error: "Búsqueda vacía" }, 400);
      const page = Math.min(Math.max(parseInt(b.page) || 1, 1), 10);
      const body = { q, num: 10, page, hl: "es" };
      if (/^[a-z]{2}$/.test(b.gl || "")) body.gl = b.gl;

      const r = await fetch("https://google.serper.dev/search", {
        method: "POST",
        headers: { "X-API-KEY": env.SERPER_KEY, "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
      let d = {};
      try { d = await r.json(); } catch (e) {}
      if (!r.ok) return json({ error: d.message || "Error de Serper (" + r.status + ")" }, r.status);
      return json({
        organic: (d.organic || []).map((o) => ({ title: o.title, link: o.link, snippet: o.snippet })),
      });
    }

    return new Response(getHtml(), {
      headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "no-cache" },
    });
  },
};
